  { title: 'شب ویلا', place: 'یک ویلای باغ‌دار', role: 'صاحب ویلا', rooms: ['ایوان', 'زیرزمین', 'کنار استخر', 'گاراژ'], open: 'مهمانان برای شام دور هم جمع شدند.', cut: 'چراغ‌های حیاط چند دقیقه خاموش شد.', items: ['دسته‌کلید', 'دستکش باغبانی', 'یک لیوان خالی'] }
