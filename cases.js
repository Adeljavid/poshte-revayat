const NAMES = ['سارا', 'مانی', 'نیلوفر', 'آرمان', 'رها', 'کیان', 'پگاه', 'سینا', 'مهسا', 'بابک', 'لیلا', 'پوریا', 'آتنا', 'فرهاد', 'ندا', 'امیر', 'شیدا', 'کامران', 'بهرام', 'یونس'];
