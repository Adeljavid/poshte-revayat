const REASONS = ['منتظر یک تماس بودم', 'دنبال وسیله‌ام می‌گشتم', 'با یک نفر صحبت می‌کردم', 'کمی استراحت می‌کردم', 'کاری را تحویل می‌دادم', 'هوا می‌خوردم'];
