const DET_LINES = ['از هر نفر بپرس آخرین بار قربانی را کِی و کجا دید.', 'دو نفر را که حرفشان با هم نمی‌خواند رو‌به‌رو کن.', 'ادعاهای هم‌زمان را کنار هم بگذار و ناهماهنگی را پیدا کن.', 'از یکی بپرس: «چه کسی می‌تواند حرفت را تأیید کند؟»'];
