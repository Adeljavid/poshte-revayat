function makeCase(n, roles) {
  const S = pick(SETTINGS), names = shuffle(NAMES), rels = shuffle(RELATIONS), topics = shuffle(TOPICS);
  const victimName = names.pop(), victim = `${victimName}، ${S.role}`;
  const base = 1020 + 5 * Math.floor(Math.random() * 43);
  const scene = pick(S.rooms), argRoom = pick(S.rooms), item = pick(S.items);
  const slots = shuffle([5, 10, 15, 20, 25, 30]);
  const chars = Array.from({ length: n }, (_, i) => ({
    name: names[i], rel: rels[i % rels.length], topic: topics[i % topics.length],
    t: base + slots[i % slots.length], room: pick(S.rooms.filter(r => r !== scene)), why: pick(REASONS)
  }));
  const k = roles.indexOf('قاتل');
  const timeline = [
    `${fmt(base)} — ${S.open}`,
    `${fmt(base + 15)} — صدای بحث از ${argRoom} شنیده شد.`,
    `${fmt(base + 25)} — ${S.cut}`,
    `${fmt(base + 40)} — ${victimName} در ${scene} پیدا شد.`
  ];
  const others = chars.map((c, i) => i).filter(i => i !== k);
  const clues = [];
  if (k >= 0) {
    const c = chars[k];
    clues.push(`${item} در ${scene} پیدا شد؛ شاهدی آن را ساعت ${fmt(c.t)} همان‌جا دیده، در حالی که یکی از حاضران می‌گوید آن لحظه در ${c.room} بوده.`);
    clues.push(`${c.topic.obj} نزدیک ${scene} پیدا شد؛ موضوع آن به «${c.topic.n}» برمی‌گردد.`);
  }
  others.slice(0, 2).forEach(i => clues.push(`${chars[i].topic.obj} در ${pick(S.rooms)} پیدا شد؛ موضوع آن به «${chars[i].topic.n}» برمی‌گردد.`));
  const cards = chars.map((c, i) => {
    const role = roles[i];
    const task = role === 'قاتل' ? `حقیقت پنهان: ساعت ${fmt(c.t)} در ${scene} بودی و ادعایت درباره‌ی ${c.room} دروغ است. هویتت را فاش نکن و شک را به سمت دیگران ببر.`
      : role === 'کارآگاه' ? 'تو کارآگاهی: با پرسش از همه، ادعاها را مقایسه کن و ناهماهنگی را پیدا کن.'
      : 'تو بی‌گناهی؛ رازت را هر وقت و به هر شکل که خودت صلاح می‌دانی فاش کن و برای حضورت توضیح قابل دفاع بده.';
    return {
      character: c.name, relation: c.rel,
      publicStatement: `ساعت ${fmt(c.t)} در ${c.room} بودم؛ ${c.why}.`,
      privateHook: c.topic.hook, requiredPrompt: task,
      lines: shuffle(role === 'کارآگاه' ? DET_LINES : LINES).slice(0, 3),
      improv: shuffle(IMPROV).slice(0, 2)
    };
  });
  return { title: S.title, victim, timeline, clues: shuffle(clues), cards,
    intro: `در ${S.place}، ${victimName} مرده پیدا شده است. ${fa(n)} نفر آن شب آنجا بودند و هرکدام بخشی از ماجرا را می‌دانند؛ ادعاها و زمان‌ها را با هم مقایسه کنید.` };
}
module.exports = { makeCase };
